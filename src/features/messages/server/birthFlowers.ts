export type BirthFlowerMonthDay = keyof typeof BIRTH_FLOWERS_BY_MONTH_DAY;

export function getBirthFlowerByMonthDay(monthDay: string): BirthFlower | null {
  if (!isBirthFlowerMonthDay(monthDay)) {
    return null;
  }

  return BIRTH_FLOWERS_BY_MONTH_DAY[monthDay];
}

export function getBirthFlowerForDate(date: Date, timeZone = "Asia/Tokyo"): BirthFlower | null {
  return getBirthFlowerByMonthDay(formatMonthDayKey(date, timeZone));
}

export function getBirthFlowerSourceUrl(monthDay: string): string | null {
  if (!isBirthFlowerMonthDay(monthDay)) {
    return null;
  }

  const [month, day] = monthDay.split("-");

  return BIRTH_FLOWER_SOURCE.url + month + "/" + day + "/";
}

export function formatMonthDayKey(date: Date, timeZone = "Asia/Tokyo") {
  const parts = new Intl.DateTimeFormat("en-US", {
    day: "2-digit",
    month: "2-digit",
    timeZone,
  }).formatToParts(date);
  const month = parts.find((part) => part.type === "month")?.value;
  const day = parts.find((part) => part.type === "day")?.value;

  if (!month || !day) {
    throw new Error("Could not format month-day key.");
  }

  return month + "-" + day;
}

function isBirthFlowerMonthDay(monthDay: string): monthDay is BirthFlowerMonthDay {
  return Object.prototype.hasOwnProperty.call(BIRTH_FLOWERS_BY_MONTH_DAY, monthDay);
}
